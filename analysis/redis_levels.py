#!/usr/bin/env python3
"""Classify each redis run onto its latency level from redis's event-loop cycles (plan R18).

Usage (from the repo root; WSL or Linux):
    python3 -I analysis/redis_levels.py [--threshold 0.94] [--band 0.93 0.96]

Reads every redis-memtier/{perf,ebpf,collector}/results*/redis_<m>.csv that exists
(block 1 is results/, block 2 is results-block2/), skips warm-up rows (role W*),
and writes:
    analysis/results/redis_L_levels.csv   one row per analysed run
    analysis/results/redis_L_levels.md    per-cell counts and the borderline runs

Rule. A run's cycles per second is redis_loop_cycles_delta / window_s. It is divided by
a reference, the median cycles per second of comparable runs:
  - untraced runs (A1, A2): all untraced runs at the same rate in the same block, pooled
    over every cell and mechanism (the untraced condition is the same in all of them);
  - traced runs (B*): the other traced runs of the same cell (mechanism, scope, rate,
    block), including the run itself. Tracing lowers cycles per second by itself
    (perf wide at 10000 req/s: about 364 against about 595 untraced), so traced runs
    cannot be judged against an untraced reference.
A run whose ratio is below THRESHOLD is on the second level. Runs with a ratio inside
BAND are listed as borderline so a sensitivity check can be repeated at either edge.

Why 0.94. It comes from the 1-thread diagnostics, not from matrix data. There, untraced
second-level runs sat at 0.884 (2500 req/s, diag/20261112-185303) and 0.893 (5000 req/s,
diag/20261112-194555) of the main level's median, and main-level runs never went below
0.980. The midpoint of 1.0 and the second level (about 0.889) is 0.944; the midpoint of
the gap's edges (0.980, 0.894) is 0.937. 0.94 sits between them.

Deterministic; no random numbers. Second-level runs are never dropped from the data;
this only labels them (R18: all runs primary, without second-level runs as a
labelled sensitivity check).
"""
import argparse
import csv
import os
import statistics
import sys

MECHS = ("perf", "ebpf", "collector")
BLOCK_DIRS = (("1", "results"), ("2", "results-block2"))
FIELDS = ("block", "run_id", "mechanism", "scope", "rate_target", "role", "traced",
          "cycles_per_s", "ref_cycles_per_s", "ratio", "level", "borderline", "p99_ms")


def cycles_per_s(row):
    return float(row["redis_loop_cycles_delta"]) / float(row["window_s"])


def classify(rows, threshold=0.94, band=(0.93, 0.96)):
    """rows: dicts with block, mechanism, scope, rate_target, role, traced,
    redis_loop_cycles_delta, window_s. Returns new dicts with the FIELDS keys."""
    rows = [r for r in rows if not r["role"].startswith("W")]
    refs = {}
    for r in rows:
        if r["traced"] == "1":
            key = ("B", r["block"], r["mechanism"], r["scope"], r["rate_target"])
        else:
            key = ("A", r["block"], r["rate_target"])
        refs.setdefault(key, []).append(cycles_per_s(r))
    out = []
    for r in rows:
        key = (("B", r["block"], r["mechanism"], r["scope"], r["rate_target"])
               if r["traced"] == "1" else ("A", r["block"], r["rate_target"]))
        cps = cycles_per_s(r)
        ref = statistics.median(refs[key])
        ratio = cps / ref
        out.append({
            "block": r["block"], "run_id": r["run_id"], "mechanism": r["mechanism"],
            "scope": r["scope"], "rate_target": r["rate_target"], "role": r["role"],
            "traced": r["traced"], "cycles_per_s": f"{cps:.2f}",
            "ref_cycles_per_s": f"{ref:.2f}", "ratio": f"{ratio:.4f}",
            "level": "second" if ratio < threshold else "main",
            "borderline": "1" if band[0] <= ratio <= band[1] else "0",
            "p99_ms": r.get("p99_ms", "NA"),
        })
    return out


def load(root):
    rows = []
    for mech in MECHS:
        for block, sub in BLOCK_DIRS:
            path = os.path.join(root, "redis-memtier", mech, sub, f"redis_{mech}.csv")
            if not os.path.exists(path):
                continue
            with open(path, newline="") as f:
                for r in csv.DictReader(f):
                    r["block"] = block
                    rows.append(r)
    return rows


def report(out, threshold, band):
    cells = {}
    for o in out:
        k = (o["block"], o["mechanism"], o["scope"], int(o["rate_target"]), o["traced"])
        n, s = cells.get(k, (0, 0))
        cells[k] = (n + 1, s + (o["level"] == "second"))
    second = [o for o in out if o["level"] == "second"]
    border = [o for o in out if o["borderline"] == "1"]
    lines = [
        "# redis latency levels (Platform L)",
        "",
        "Generated by `analysis/redis_levels.py`; do not edit by hand. Rule and the",
        f"reason for the threshold are in the script's docstring. Threshold {threshold},",
        f"borderline band {band[0]}–{band[1]} (ratio of a run's event-loop cycles per",
        "second to the median of comparable runs).",
        "",
        f"Runs analysed: {len(out)} (warm-ups excluded). On the second level: {len(second)}.",
        f"Borderline: {len(border)}.",
        "",
        "## Second-level runs per cell",
        "",
        "| block | mechanism | scope | rate (req/s) | untraced (second/all) | traced (second/all) |",
        "|---|---|---|---|---|---|",
    ]
    for (b, m, s, rate) in sorted({k[:4] for k in cells}, key=lambda k: (k[0], MECHS.index(k[1]), k[2], k[3])):
        a = cells.get((b, m, s, rate, "0"), (0, 0))
        t = cells.get((b, m, s, rate, "1"), (0, 0))
        lines.append(f"| {b} | {m} | {s} | {rate} | {a[1]}/{a[0]} | {t[1]}/{t[0]} |")
    for title, rows in (("Second-level runs", second), ("Borderline runs", border)):
        lines += ["", f"## {title}", ""]
        if not rows:
            lines.append("None.")
            continue
        lines += ["| run | cycles/s | reference | ratio | level | p99 (ms) |", "|---|---|---|---|---|---|"]
        for o in rows:
            lines.append(f"| {o['run_id']} (block {o['block']}) | {o['cycles_per_s']} | "
                         f"{o['ref_cycles_per_s']} | {o['ratio']} | {o['level']} | {o['p99_ms']} |")
    return "\n".join(lines) + "\n"


def main(argv=None):
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--root", default=os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
    ap.add_argument("--threshold", type=float, default=0.94)
    ap.add_argument("--band", type=float, nargs=2, default=(0.93, 0.96))
    a = ap.parse_args(argv)
    rows = load(a.root)
    if not rows:
        sys.exit("no redis results found")
    out = classify(rows, a.threshold, tuple(a.band))
    res = os.path.join(a.root, "analysis", "results")
    with open(os.path.join(res, "redis_L_levels.csv"), "w", newline="") as f:
        w = csv.DictWriter(f, fieldnames=FIELDS, lineterminator="\n")
        w.writeheader()
        w.writerows(out)
    with open(os.path.join(res, "redis_L_levels.md"), "w", newline="\n") as f:
        f.write(report(out, a.threshold, tuple(a.band)))
    print(f"{len(out)} runs, {sum(o['level'] == 'second' for o in out)} second-level, "
          f"{sum(o['borderline'] == '1' for o in out)} borderline")


if __name__ == "__main__":
    main()
