#!/usr/bin/env python3
"""Why does the collector make redis cheaper? (Platform L, README timeline 69)

Usage (from the repository root; WSL):
    python3 -I analysis/redis_collector_check.py    # writes analysis/results/redis_L_collector_check.md

The two-block test (timeline 67) found redis CPU 0.2-1.3 % LOWER with the
collector attached, in 7 of 8 cells. This script asks two questions, from the
committed redis CSVs of both blocks; exploratory, no test.
  1. Order effect? Per cell and block, each run's redis CPU in % of
     mean(A1, A2), in run order A1, B1..B6, A2. A time trend inside the
     bracket would show as A1 and A2 apart; a real effect as every B apart
     from both A runs.
  2. What else moves? For each mechanism and scope: the mean over the 8 cells
     (both blocks) of 100 x (mean traced / mean untraced - 1) for package
     power, frequency, workload-core busy %, interrupts on workload cores,
     timer interrupts, redis event-loop cycles and p50.
Pure standard library; deterministic.
"""
import csv
import os
import platform
import statistics as S
import subprocess
import sys

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from nginx_stats import sha256  # noqa: E402

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SUBS = ["results", "results-block2"]
ORDER = ["A1", "B1", "B2", "B3", "B4", "B5", "B6", "A2"]
COLS = ["workload_cpu_cores", "pkg_watts_mean", "freq_max_khz", "freq_min_khz", "busy_pct_workload",
        "irq_workload_delta", "irq_timer_delta", "redis_loop_cycles_delta", "p50_ms"]
OUT = os.path.join(ROOT, "analysis", "results", "redis_L_collector_check.md")


def rows(mech, sub):
    with open(os.path.join(ROOT, "redis-memtier", mech, sub, f"redis_{mech}.csv"), newline="") as f:
        return list(csv.DictReader(f))


def main():
    rels = [f"redis-memtier/{m}/{s}/redis_{m}.csv" for m in ("perf", "ebpf", "collector") for s in SUBS]
    head = run_head(rels)
    md = ["# redis: why the collector lowers redis CPU (generated — do not edit by hand)", ""]
    md += [h + "  " for h in head]
    md += ["", "Method: docstring of `analysis/redis_collector_check.py`. Exploratory; nothing is tested.", "",
           "## 1. Collector: redis CPU per run, % of mean(A1, A2), in run order", "",
           "| block | scope | level | " + " | ".join(ORDER) + " |", "|---" * (3 + len(ORDER)) + "|"]
    for blk, sub in enumerate(SUBS, 1):
        cells = {}
        for r in rows("collector", sub):
            cells.setdefault((r["scope"], r["level"]), {})[r["role"]] = r
        for (sc, lv), c in sorted(cells.items()):
            ma = (float(c["A1"]["workload_cpu_cores"]) + float(c["A2"]["workload_cpu_cores"])) / 2
            md.append(f"| {blk} | {sc} | E{lv} | " + " | ".join(
                f"{100 * (float(c[o]['workload_cpu_cores']) / ma - 1):+.1f}" for o in ORDER) + " |")
    md += ["", "## 2. Mean traced/untraced change over 8 cells (both blocks), %", "",
           "| mechanism | scope | " + " | ".join(COLS) + " |", "|---" * (2 + len(COLS)) + "|"]
    for mech in ("collector", "perf", "ebpf"):
        for sc in ("narrow", "wide"):
            acc = {k: [] for k in COLS}
            for sub in SUBS:
                cells = {}
                for r in rows(mech, sub):
                    if r["scope"] == sc:
                        cells.setdefault(r["level"], []).append(r)
                for rs in cells.values():
                    for k in COLS:
                        a = S.mean(float(r[k]) for r in rs if r["traced"] == "0")
                        b = S.mean(float(r[k]) for r in rs if r["traced"] == "1")
                        acc[k].append(100 * (b / a - 1))
            md.append(f"| {mech} | {sc} | " + " | ".join(f"{S.mean(v):+.2f}" for v in acc.values()) + " |")
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(md) + "\n")
    print("wrote", os.path.relpath(OUT, ROOT))


def run_head(rels):
    try:
        h = subprocess.run(["git", "-C", ROOT, "rev-parse", "--short=8", "HEAD"],
                           capture_output=True, text=True, check=True).stdout.strip()
    except Exception:
        h = "unknown"
    return ([f"generated by analysis/redis_collector_check.py at harness commit {h}",
             f"python {platform.python_version()} ({platform.python_implementation()}), standard library only"]
            + [f"input {r} sha256 {sha256(os.path.join(ROOT, r))}" for r in rels])


if __name__ == "__main__":
    main()
